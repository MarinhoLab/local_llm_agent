class AgentServer:
    def __init__(self, base_url: str, api_key: str):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key

    def _headers(self) -> dict:
        return {"X-Session-API-Key": self.api_key}

    def list_conversations(self, max_items: int = 500) -> list[dict]:
        """List all conversations, paginating (the API caps `limit` at 100)."""
        items: list[dict] = []
        page_id: str | None = None
        while True:
            url = f"{self.base_url}/api/conversations/search?limit=100"
            if page_id:
                url += f"&page_id={page_id}"
            status, body = http_request(url, headers=self._headers())
            if status != 200:
                raise RuntimeError(
                    f"GET conversations failed: HTTP {status} ({body[:200]!r})"
                )
            data = json.loads(body)
            page = data.get("items") or data.get("events") or []
            items.extend(page)
            if len(items) >= max_items or len(page) < 100:
                break
            page_id = data.get("next_page_id") or data.get("page_id")
            if not page_id:
                break
        return items

    def recent_messages(self, conv_id: str, limit: int = 100) -> list[str]:
        """Return recent assistant/user message texts (newest last).

        Tolerant of API shape: reads MessageEvent.llm_message.content which is
        a list of blocks like {"type": "text", "text": "..."} or a string.
        """
        url = f"{self.base_url}/api/conversations/{conv_id}/events/search?limit={limit}"
        try:
            status, body = http_request(url, headers=self._headers())
        except ConnectionError:
            return []
        if status != 200:
            return []
        data = json.loads(body)
        events = data.get("events") or data.get("items") or []
        texts: list[str] = []
        for e in events:
            if e.get("kind") != "MessageEvent":
                continue
            llm = e.get("llm_message") or {}
            content = llm.get("content")
            parts: list[str] = []
            if isinstance(content, str):
                parts.append(content)
            elif isinstance(content, list):
                for block in content:
                    if isinstance(block, dict) and block.get("type") == "text":
                        parts.append(str(block.get("text", "")))
            text = "\n".join(p for p in parts if p).strip()
            if text:
                texts.append(f"{llm.get('role', '?')}: {text}")
        return texts

    def recent_error(self, conv_id: str, limit: int = 50) -> str:
        """Return the most recent AgentErrorEvent error text (or '')."""
        url = f"{self.base_url}/api/conversations/{conv_id}/events/search?limit={limit}"
        try:
            status, body = http_request(url, headers=self._headers())
        except ConnectionError:
            return ""
        if status != 200:
            return ""
        data = json.loads(body)
        events = data.get("events") or data.get("items") or []
        errors: list[str] = []
        for e in events:
            if e.get("kind") != "AgentErrorEvent":
                continue
            err = e.get("error")
            if isinstance(err, str) and err.strip():
                errors.append(err.strip())
            elif isinstance(err, dict):
                errors.append(json.dumps(err, ensure_ascii=False))
        return errors[-1] if errors else ""


