class Notifier:
    def __init__(self, args=None):
        self.base_url = env("NTFY_BASE_URL", "http://127.0.0.1:18000")
        self.poll_seconds = float(env("NTFY_POLL_SECONDS", "5") or 5)
        self.cooldown = float(env("NTFY_COOLDOWN_SECONDS", "120") or 120)
        self.include_message = env_bool("NTFY_INCLUDE_MESSAGE", True)
        self.dry_run = env_bool("NTFY_DRY_RUN", False)
        self.state_path = Path(
            env("NTFY_STATE_FILE", "")
        ) if env("NTFY_STATE_FILE") else None

        # statuses to notify on (whitelist)
        raw_events = env("NTFY_EVENTS", "")
        if raw_events:
            self.events = {s.strip() for s in raw_events.split(",") if s.strip()}
            unknown = self.events - KNOWN_STATUSES
            if unknown:
                log(f"WARNING: unknown status(es) in NTFY_EVENTS: {unknown}")
        else:
            self.events = set(DEFAULT_EVENTS)

        self.publisher = NtfyPublisher(
            server=env("NTFY_SERVER", "http://127.0.0.1:2020"),
            topic=env("NTFY_TOPIC", "agent-canvas"),
            token=env("NTFY_AUTH_TOKEN", ""),
            topic_mode=env("NTFY_TOPIC_MODE", "shared"),
            hostname=self._hostname(),
            deep_link_prefix=env("NTFY_DEEP_LINK_PREFIX", ""),
            max_body=int(env("NTFY_MAX_BODY", str(min(4000, NTFY_MESSAGE_LIMIT)))
                        or 4000),
            dry_run=self.dry_run,
        )

        self._stop = False
        self._api_key: str | None = None
        self.server: AgentServer | None = None

    # -- key resolution -----------------------------------------------------

    @staticmethod
    def _hostname() -> str:
        val = env("NTFY_HOSTNAME", "")
        if val:
            return val
        if hasattr(os, "uname"):
            return os.uname().nodename
        return os.environ.get("HOSTNAME", "agent")

    def resolve_api_key(self) -> str:
        for var in ("OH_SESSION_API_KEYS_0", "LOCAL_BACKEND_API_KEY"):
            val = os.environ.get(var, "").strip()
            if val:
                return val
        key_file = Path.home() / ".openhands" / "agent-canvas" / "api-key.txt"
        if key_file.exists():
            val = key_file.read_text(encoding="utf-8").strip()
            if val:
                return val
        return ""

    def ensure_server(self) -> bool:
        """(Re)create the AgentServer handle once the key is available.

        The launcher writes api-key.txt on first start; if the notifier
        starts slightly earlier, wait for the file to appear.
        """
        if self.server is not None:
            return True
        key = self.resolve_api_key()
        if not key:
            return False
        self._api_key = key
        self.server = AgentServer(self.base_url, key)
        log(f"connected to agent-server at {self.base_url}")
        return True

    # -- notification building ----------------------------------------------

    def build_snippet(self, conv_id: str, status: str) -> str:
        if not self.include_message or self.server is None:
            return ""
        # For errors, surface the actual error text (AgentErrorEvent) rather
        # than the last message — it's the actionable part.
        if status == "error":
            try:
                err = self.server.recent_error(conv_id, limit=100)
            except Exception:
                err = ""
            if err:
                if len(err) > 900:
                    err = "… " + err[-900:]
                return err
        try:
            messages = self.server.recent_messages(conv_id, limit=100)
        except Exception:
            return ""
        # Prefer the most recent assistant message; fall back to any message.
        assistant = [m for m in messages if m.startswith("assistant:")]
        pick = assistant[-1] if assistant else (messages[-1] if messages else "")
        pick = pick.strip()
        if not pick:
            return ""
        if len(pick) > 900:
            pick = "… " + pick[-900:]
        return pick

    def _cooldown_ok(self, state: dict, key: str) -> bool:
        last = state.get("last_notified", {}).get(key, 0)
        return (time.time() - last) >= self.cooldown

    def _record(self, state: dict, key: str) -> None:
        state.setdefault("last_notified", {})[key] = time.time()

    # -- main loop -----------------------------------------------------------

    def poll_once(self, state: dict, force_all: bool = False) -> None:
        if self.server is None:
            return
        try:
            conversations = self.server.list_conversations()
        except (ConnectionError, RuntimeError) as e:
            log(f"WARN: could not list conversations: {e}")
            return

        now = time.time()
        seen: set[str] = set()
        for conv in conversations:
            cid = conv.get("id")
            status = conv.get("execution_status")
            if not cid or not status:
                continue
            seen.add(cid)

            prev = state["conversations"].get(cid, {})
            prev_status = prev.get("status")

            # First sighting: record, but only notify on force_all or if the
            # conversation is already in a terminal/attention status (catch-up
            # after the notifier was restarted).
            first_sight = prev_status is None
            interesting = status in self.events
            should_notify = (
                force_all
                or (
                    interesting
                    and (prev_status != status)
                    and (not first_sight or self.cooldown <= 0)
                )
            )

            # Update tracked status (only on change, to avoid churn).
            if prev_status != status:
                state["conversations"][cid] = {
                    "status": status,
                    "updated_at": now,
                    "title": conv.get("title", ""),
                }

            if should_notify:
                key = f"{cid}:{status}"
                # force_all is a manual re-test (SIGUSR1): bypass the cooldown.
                if force_all or self._cooldown_ok(state, key):
                    snippet = self.build_snippet(cid, status)
                    try:
                        self.publisher.publish(conv, status, snippet)
                        self._record(state, key)
                    except (ConnectionError, OSError) as e:
                        log(f"WARN: publish error: {e}")

        # Drop conversations that disappeared (deleted) to keep state small.
        stale = [c for c in list(state["conversations"]) if c not in seen]
        if stale:
            for c in stale:
                del state["conversations"][c]
            # prune old cooldown keys
            cutoff = now - max(self.cooldown * 10, 3600)
            state.setdefault("last_notified", {})
            for k in [
                k for k, v in state["last_notified"].items() if v < cutoff
            ]:
                del state["last_notified"][k]

    def run(self) -> int:
        log(
            f"ntfy_notifier v{VERSION} starting — "
            f"agent-server={self.base_url} ntfy={self.publisher.server} "
            f"topic={self.publisher.base_topic!r} mode={self.publisher.topic_mode} "
            f"events={sorted(self.events)} dry_run={self.dry_run}"
        )
        if self.state_path is None:
            # Default: <cwd>/openhands-state/ntfy_notifier_state.json. run.sh
            # sets NTFY_STATE_FILE explicitly; this is a safe fallback.
            self.state_path = Path(
                env("NTFY_STATE_FILE", "")
            ) or Path("openhands-state") / "ntfy_notifier_state.json"

        signal.signal(signal.SIGTERM, self._handle_signal)
        signal.signal(signal.SIGINT, self._handle_signal)
        signal.signal(signal.SIGUSR1, self._handle_usr1)

        # Wait for the API key (launcher may still be writing it).
        wait_start = time.time()
        while not self.ensure_server():
            if time.time() - wait_start > 300:
                log("ERROR: no session API key found after 300s; exiting.")
                return 1
            log("waiting for agent-server session API key...")
            time.sleep(2)

        state = load_state(self.state_path)
        log(f"state file: {self.state_path}")

        last_save = 0.0
        while not self._stop:
            t0 = time.time()
            try:
                self.poll_once(state)
            except Exception as e:  # noqa: BLE001 - daemon must keep running
                log(f"ERROR in poll loop: {e}")
            # Persist state at most every 5s and on meaningful changes.
            if t0 - last_save >= 5:
                save_state(self.state_path, state)
                last_save = t0
            # Sleep in small increments so Ctrl+C is responsive.
            deadline = t0 + self.poll_seconds
            while not self._stop and time.time() < deadline:
                time.sleep(0.2)

        save_state(self.state_path, state)
        log("stopped.")
        return 0

    def _handle_signal(self, signum, _frame):
        log(f"received signal {signum}; stopping...")
        self._stop = True

    def _handle_usr1(self, signum, _frame):
        log("SIGUSR1: force-publishing current statuses")
        if self.state_path is not None:
            state = load_state(self.state_path)
            self.poll_once(state, force_all=True)
            save_state(self.state_path, state)


def main() -> int:
    if not env_bool("NTFY_ENABLED", False):
        log("NTFY_ENABLED is not set — nothing to do (this is expected when")
        log("ntfy notifications are disabled).")
        return 0
    notifier = Notifier()
    return notifier.run()


if __name__ == "__main__":
    sys.exit(main())
