class NtfyPublisher:
    def __init__(
        self,
        server: str,
        topic: str,
        token: str = "",
        topic_mode: str = "shared",
        hostname: str = "",
        deep_link_prefix: str = "",
        max_body: int = 4000,
        dry_run: bool = False,
    ):
        self.server = server.rstrip("/")
        self.base_topic = topic.strip()
        self.token = token
        self.topic_mode = topic_mode
        self.hostname = hostname
        self.deep_link_prefix = deep_link_prefix.rstrip("/")
        self.max_body = max_body
        self.dry_run = dry_run

    def _auth_headers(self) -> dict:
        if not self.token:
            return {}
        # ntfy accepts Bearer for access tokens.
        return {"Authorization": f"Bearer {self.token}"}

    def _topic_for(self, conv: dict) -> str:
        if self.topic_mode == "one-per-conv":
            return f"{self.base_topic}-{conv['id'][:8]}"
        return self.base_topic

    def _title_for(self, conv: dict, title: str) -> str:
        # one-per-PC mode: every notification is prefixed with the host.
        # shared mode: the topic already separates PCs, but still label so a
        # forwarded/logged message is attributable.
        if self.hostname and self.topic_mode == "one-per-PC":
            return f"{self.hostname}: {title}"
        return title

    def publish(
        self,
        conv: dict,
        status: str,
        snippet: str = "",
        cooldown_key: str | None = None,
    ) -> None:
        preset = NOTIFICATION_PRESETS.get(status)
        if preset is None:
            title, priority, tags, link_suffix, emoji = (
                f"Agent status: {status}",
                2,
                "robot",
                None,
                "•",
            )
        else:
            title, priority, tags, link_suffix, emoji = preset

        conv_title = (conv.get("title") or conv["id"][:12]).strip()
        title = f"{title} — {conv_title}" if conv_title != conv["id"][:12] else title
        title = self._title_for(conv, title)

        click = None
        if self.deep_link_prefix:
            click = f"{self.deep_link_prefix}/{conv['id']}"
            if link_suffix:
                click = f"{click}{link_suffix}"

        body = snippet.strip()
        if len(body) > self.max_body:
            body = body[: self.max_body - 1] + "…"

        headers = {
            "Title": rfc2047_header(title),
            "Priority": str(priority),
            "Tags": rfc2047_header(tags),
            **self._auth_headers(),
        }
        if click:
            headers["Click"] = click

        topic = self._topic_for(conv)
        url = f"{self.server}/{topic}"

        if self.dry_run:
            log(
                f"DRY-RUN publish to {url} :: title={title!r} "
                f"priority={priority} tags={tags} click={click} body={body[:80]!r}"
            )
            return

        status_code, resp = http_request(
            url,
            method="PUT",
            headers=headers,
            body=body.encode("utf-8"),
        )
        if status_code >= 400:
            # Do not dump the body — it may echo back our auth header.
            log(f"WARN: ntfy publish failed HTTP {status_code}")
        else:
            log(
                f"published {status} for conversation {conv['id'][:8]} "
                f"(topic={topic}, priority={priority})"
            )


