#!/usr/bin/env python3
"""ntfy_notifier.py — push Agent Canvas status changes to ntfy.

A small daemon that watches the local Agent Canvas agent-server
(conversations' execution_status) and publishes ntfy notifications when a
conversation transitions into a status of interest (finished, idle = waiting
for input, error, stuck, ...).

It is intentionally dependency-free (Python stdlib only) so it can run on
any PC next to Agent Canvas without a venv.

Configuration (environment variables, normally set in agent_canvas_native/.env
by run.sh):

    NTFY_ENABLED=false        # set true to run this daemon
    NTFY_SERVER=http://127.0.0.1:2020   # or https://ntfy.sh for the public server
    NTFY_TOPIC=agent-canvas   # topic to publish to (unguessable!)
    NTFY_AUTH_TOKEN=          # access token for a protected/self-hosted server
    NTFY_TOPIC_MODE=shared    # shared | one-per-PC | one-per-conv
    NTFY_HOSTNAME=            # machine label, default: os hostname
    NTFY_DEEP_LINK_PREFIX=    # e.g. http://mac.tail:8020/conversations/
    NTFY_POLL_SECONDS=5       # poll interval
    NTFY_COOLDOWN_SECONDS=120 # per-(conversation,status) re-notify cooldown
    NTFY_MAX_BODY=4000        # max message body chars (ntfy hard limit is 4096B)
    NTFY_PRIORITIES=idle=3,finished=3,error=5,stuck=4,waiting_for_confirmation=4
    NTFY_EVENTS=              # comma list of statuses to notify on
                              # (default: idle,finished,error,stuck,waiting_for_confirmation)
    NTFY_INCLUDE_MESSAGE=true # include a snippet of the last agent message
    NTFY_BASE_URL=http://127.0.0.1:18000   # agent-server (via ingress or direct)

The agent-server session API key is read (never printed) in this order:
  1. $OH_SESSION_API_KEYS_0 / $LOCAL_BACKEND_API_KEY
  2. ~/.openhands/agent-canvas/api-key.txt (auto-generated by the launcher)

State (last-seen status per conversation, with timestamps for cooldowns)
lives in <state_dir>/ntfy_notifier_state.json next to the Agent Canvas state,
so nothing depends on memory across restarts.

Signal handling: SIGTERM/SIGINT stop the loop cleanly; SIGUSR1 (re)publishes
the current status snapshot for every watched conversation (useful to
re-test the pipeline after changing phone settings).
"""

